// Captures every screen and key state at iPhone 15 size: node screens.mjs <outdir>
import { webkit, devices } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { seed, localDate, FOODS, SENTENCE } from './fixtures.mjs';
const out = process.argv[2]; mkdirSync(out, { recursive: true });
const b = await webkit.launch();
const ctx = await b.newContext({ ...devices['iPhone 15'], colorScheme: 'dark' });
const p = await ctx.newPage();
const shot = async name => { await p.waitForTimeout(350); await p.screenshot({ path: `${out}/${name}.png` }); };
await p.goto('http://127.0.0.1:8137/index.html'); await p.waitForSelector('.tabbar .tab');
await shot('01-empty-first-run');
const y = localDate(-1), t = localDate(0);
const e = (id, date, meal, foodId, qty) => ({ id, date, meal, foodId, qty });
const day = (d, k) => [e(k+1, d, 1, 'wb', 2), e(k+2, d, 1, 'gm', 200), e(k+3, d, 1, 'wp', 1), e(k+4, d, 2, 'cb', 125), e(k+5, d, 2, 'br', 150), e(k+6, d, 2, 'cs', 20)];
const weights = [-29, -22, -15, -8, -1].map((o, i) => ({ date: localDate(o), kg: [84.1, 83.6, 83.2, 83.0, 82.5][i] }));
await seed(p, { foods: FOODS, entries: [...day(y, 'y'), ...day(t, 't').slice(0, 3)], weights });
await shot('02-diary-weigh-in-due');
await p.evaluate(() => document.querySelector('main').scrollTo(0, 9999)); await p.evaluate(() => window.scrollTo(0, 9999));
await shot('03-diary-scrolled');
await p.evaluate(() => window.scrollTo(0, 0));
await p.getByRole('button', { name: /Dictate/ }).click();
await p.getByLabel('What you ate').pressSequentially(SENTENCE.replace('Meal number one', 'Meal number three').replace('Meal number two', 'Meal number four') + ' And 3 bananas.');
await shot('04-dictate-live');
await p.locator('.sheet').getByRole('button', { name: 'Save' }).click();
await shot('05-confirm');
await p.locator('.sheet').getByRole('button', { name: 'Cancel' }).click();
await p.locator('.sheet').getByRole('button', { name: 'Cancel' }).click();
await p.getByRole('button', { name: 'Add food' }).first().click();
await shot('06-add-food-sheet');
await p.locator('.sheet').getByText('Chicken breast').click();
await shot('07-add-food-qty');
await p.locator('.sheet').getByRole('button', { name: 'Cancel' }).click();
await p.getByLabel('Morning weight in kg').fill('82.1'); await p.getByRole('button', { name: 'Log' }).click();
await shot('08-diary-weighed');
await p.locator('.tabbar').getByRole('button', { name: 'Foods' }).click(); await shot('09-foods');
await p.locator('.dock').getByRole('button', { name: 'Add food' }).click(); await shot('10-food-edit');
await p.locator('.sheet').getByRole('button', { name: 'Cancel' }).click();
await p.locator('.tabbar').getByRole('button', { name: 'Weight' }).click(); await shot('11-weight');
await p.getByRole('button', { name: 'Settings' }).click(); await shot('12-settings');
await p.evaluate(() => window.scrollTo(0, 9999)); await shot('13-settings-scrolled');
await b.close();
console.log('done');
